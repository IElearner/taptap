local Game=require "network.Standalone"
local Store=require "game.SaveStore"
local Data=require "game.SaveData"
V.atFrame(6,function()
    Game.UseStore(Store.new({now=function() return 1000 end,read=function() return nil end,
        write=function() return true end}),true)
end)
V.atFrame(9,function()
    local state,_,hud=Game.Inspect()
    V.assert(not hud.root:FindById("mentorDialogue"):IsVisible(),"Elder remains hidden behind login and mode choice")
    hud.root:FindById("loginGuest").props.onClick()
    state,_,hud=Game.Inspect()
    hud.root:FindById("enterVillage").props.onClick();hud.update()
    local elder=hud.root:FindById("mentorDialogue")
    V.assert(state.started and elder:IsVisible(),"Elder greets a fresh village after entering")
    V.assert(hud.root:FindById("mentorPortrait")~=nil,"Elder has a distinct portrait")
    V.assert(state.lesson==1 and not state.skipped,"Fresh village begins at the first guided task")
    hud.root:FindById("mentorGo").props.onClick();hud.update(0.5)
    V.assert(not elder:IsVisible() and state.lesson==1,"Go to task fades the dialogue without skipping its objective")
    hud.root:FindById("questChip").props.onClick();hud.update()
    V.assert(elder:IsVisible(),"Quest chip reopens the elder's instructions")
    hud.root:FindById("mentorGo").props.onClick();hud.update(0.5)
    state.roadCount=4;hud.update()
    V.assert(elder:IsVisible() and state.lesson==1,"Elder returns when the objective is complete")
    hud.root:FindById("mentorGo").props.onClick();hud.update()
    V.assert(state.lesson==2 and elder:IsVisible(),"Continue opens the next conversation")
    hud.root:FindById("mentorSkip").props.onClick();hud.update(0.5)
    V.assert(state.skipped and state.lesson==9 and not elder:IsVisible(),"Skip immediately enables free play and fades the elder")
    local saved=Data.capture(state,1000,1,true)
    local restored=Data.restore(cjson.decode(cjson.encode(saved)),"finite")
    V.assert(restored and restored.skipped and restored.lesson==9,"Skipped tutorial persists through save/load")
    hud.root:FindById("open_village").props.onClick();hud.update()
    hud.root:FindById("restartMentor").props.onClick();hud.update()
    V.assert(not state.skipped and state.lesson==1 and elder:IsVisible(),"Village menu can replay the guided conversation")
end)
V.atFrame(25,function() V.finish() end)
