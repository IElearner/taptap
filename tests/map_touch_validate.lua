local Game=require "network.Standalone"
local Store=require "game.SaveStore"
local function worldPixel(view,sx,sy)
    local l=view.panel:GetAbsoluteLayout()
    local c=view.cameraState()
    local ox=l.x+l.w*0.53+c.x
    local oy=l.y+l.h*0.52-270*c.zoom+c.y
    return (sx-ox)/c.zoom,(sy-oy)/c.zoom
end
V.atFrame(6,function()
    Game.UseStore(Store.new({now=function() return 1000 end,read=function() return nil end,
        write=function() return true end}))
end)
V.atFrame(9,function()
    local _,view,hud=Game.Inspect()
    hud.root:FindById("enterVillage").props.onClick();hud.update()
    local controls=hud.root:FindById("mapControls")
    V.assert(controls and #controls:GetChildren()==2,"Map controls contain only Home and the pinch gesture hint")
    V.assert(controls:GetChildren()[2].props.text=="双指缩放","Map zoom is explained as a touch gesture")
    local mini=hud.root:FindById("miniMap")
    V.assert(mini and mini:IsVisible(),"Corner map is visible in landscape gameplay")
    local l=view.panel:GetAbsoluteLayout()
    local fx,fy=l.x+l.w*0.56,l.y+l.h*0.48
    local px,py=worldPixel(view,fx,fy)
    local function touch(id,x,y) return {pointerId=id,pointerType="touch",x=x,y=y} end
    view.panel.props.onPointerDown(touch(1,fx-40,fy))
    view.panel.props.onPointerDown(touch(2,fx+40,fy))
    view.panel.props.onPointerMove(touch(1,fx-56,fy))
    view.panel.props.onPointerMove(touch(2,fx+56,fy))
    local qx,qy=worldPixel(view,fx,fy)
    V.assert(math.abs(px-qx)<0.001 and math.abs(py-qy)<0.001,"Two-finger zoom keeps the map point beneath the fingers")
    V.assert(view.cameraState().zoom>1.35,"Two-finger spread zooms in")
    view.panel.props.onPointerUp(touch(1,fx-56,fy))
    view.panel.props.onPointerUp(touch(2,fx+56,fy))
    view.panel.props.onPointerDown(touch(3,fx-40,fy))
    view.panel.props.onPointerDown(touch(4,fx+40,fy))
    view.panel.props.onPointerMove(touch(3,fx-4,fy))
    view.panel.props.onPointerMove(touch(4,fx+4,fy))
    V.assert(view.cameraState().zoom==0.55,"Pinch zoom obeys readable lower bound")
    view.panel.props.onPointerUp(touch(3,fx-4,fy))
    view.panel.props.onPointerUp(touch(4,fx+4,fy))
    local panned=view.cameraState().x
    view.panel.props.onPointerDown(touch(5,fx,fy))
    view.panel.props.onPointerMove(touch(5,fx+25,fy))
    view.panel.props.onPointerUp(touch(5,fx+25,fy))
    V.assert(view.cameraState().x~=panned,"One physical finger pans the world after pinching")
    -- Drive the engine/UI input path, not only the world panel callbacks.
    local UI=require "urhox-libs/UI"
    local scale=UI.GetScale()
    view.home()
    UI.HandleTouchBegin(21,(fx-40)*scale,fy*scale)
    UI.HandleTouchBegin(22,(fx+40)*scale,fy*scale)
    UI.HandleTouchMove(21,(fx-56)*scale,fy*scale)
    UI.HandleTouchMove(22,(fx+56)*scale,fy*scale)
    V.assert(view.cameraState().zoom>1.35,"Actual UI touch dispatch delivers two-finger zoom to the map")
    UI.HandleTouchEnd(21,(fx-56)*scale,fy*scale)
    UI.HandleTouchEnd(22,(fx+56)*scale,fy*scale)
    local before=view.cameraState()
    local m=mini:GetAbsoluteLayout()
    mini.props.onTap({x=m.x+20+106*0.62,y=m.y+12+106*0.56})
    local after=view.cameraState()
    V.assert(after.x~=before.x or after.y~=before.y,"Tapping the corner map repositions the world camera")
    V.assert(after.zoom==before.zoom,"Corner navigation preserves chosen zoom")
    hud.root:FindById("open_build").props.onClick();hud.update()
    V.assert(not mini:IsVisible(),"Corner map yields its space to an open drawer")
    hud.root:FindById("open_build").props.onClick();hud.update()
    V.assert(mini:IsVisible(),"Closing the drawer brings the corner map back build=" .. tostring(hud.root:FindById("drawer_build"):IsVisible()) .. " mini=" .. tostring(mini:IsVisible()))
end)
V.atFrame(25,function() V.finish() end)
V.atFrame(12,function()
    local live,view,hud=Game.Inspect()
    hud.root:FindById("build_house").props.onClick()
    local l=view.panel:GetAbsoluteLayout()
    local c=view.cameraState()
    local function screen(x,y)
        return l.x+l.w*0.53+c.x+(x-y)*30*c.zoom,l.y+l.h*0.52-270*c.zoom+c.y+(x+y)*15*c.zoom
    end
    local sx,sy=screen(9,8)
    view.panel.props.onPointerDown({x=sx,y=sy})
    V.assert(view.previewState() and view.previewState().x==9,"Touch-down shows building preview at finger tile")
    local nx,ny=screen(8,8)
    view.panel.props.onPanMove({x=nx,y=ny,deltaX=nx-sx,deltaY=ny-sy})
    V.assert(view.previewState().x==8 and view.cameraState().x==c.x,"Dragging moves ghost without panning map")
    view.panel.props.onPanEnd({x=nx,y=ny})
    V.assert(live:buildingAt(8,8) and live:buildingAt(8,8).kind=="house","Releasing placement drag starts house construction")
    view.setMode("inspect")
    V.assert(not view.previewState(),"Leaving build mode clears ghost")
    local Sim=require "game.Simulation"
    local s=Sim.new()
    local ok,b=s:build("quarry",8,8)
    V.assert(ok,"Two-tile quarry can be placed beside starter road: " .. tostring(b))
    V.assert(s:buildingAt(7,8)==s:buildingAt(8,8),"Both quarry tiles are reserved")
    V.assert(not s:canBuild("house",7,8),"House preview rejects occupied quarry tile")
    V.assert(not s:build("road",7,8),"Road cannot cut through quarry footprint")
    hud.root:FindById("cancelPlacement").props.onClick()
    local hall=live:addBuilding("kitchen",12,8,true)
    local side=require("game.Meals").diningSide(live,hall)
    V.assert(side==1,"Dining bay chooses the open side when the store crowds its left")
    local now=view.cameraState()
    local centerX,centerY=hall.x-0.5,hall.y-0.5
    local px=l.x+l.w*0.53+now.x+((centerX-centerY)*30+side*60)*now.zoom
    local py=l.y+l.h*0.52-270*now.zoom+now.y+((centerX+centerY)*15+18)*now.zoom
    local wx,wy=worldPixel(view,px,py)
    V.assert(math.abs(wx-(120+side*60))<0.01 and math.abs(wy-303)<0.01 and live:buildingAt(12,8)==hall,
        "Dining annex tap maps back to the matching world position")
    view.panel.props.onPointerDown({pointerId=31,pointerType="touch",x=px,y=py})
    view.panel.props.onPointerUp({pointerId=31,pointerType="touch",x=px,y=py})
    view.panel.props.onTap({x=px,y=py})
    hud.update()
    local selected=view.selectedBuilding()
    V.assert(selected==hall,"Dining pavilion touch resolves to its kitchen building")
    V.assert(hud.root:FindById("drawer_selected"):IsVisible(),
        "Tapping the open dining annex opens kitchen details")
end)
